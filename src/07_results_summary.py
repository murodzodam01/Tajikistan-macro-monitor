"""Step 7: collect the key numbers into outputs/results_summary.md.

Every number quoted in the README, the note or a CV line should come from
this file, so nothing is typed in by hand.
"""

import datetime

import pandas as pd

from common import (LAST_ACTUAL_YEAR, OUTPUT_DIR, RAW_DIR, TABLE_DIR,
                    WEO_VINTAGE_LABEL, dataframe_to_markdown, read_table)

SUMMARY_FILE = OUTPUT_DIR / "results_summary.md"
SHARE_YEARS = [2000, 2010, 2020, LAST_ACTUAL_YEAR]


def percent(value):
    """Format a share (0-1) as a percentage with one decimal."""
    if pd.isna(value):
        return "n/a"
    return str(round(100 * value, 1)) + "%"


def trade_share_table(trade_w):
    """Shares of Russia, China and Kazakhstan in Tajik trade, by year."""
    tjk = trade_w[trade_w["reporter"] == "TJK"]
    rows = []
    for year in SHARE_YEARS:
        in_year = tjk[tjk["year"] == year]
        row = {"year": year}
        for partner in ["RUS", "CHN", "KAZ", "UZB"]:
            value = in_year.loc[in_year["partner"] == partner, "weight"]
            row[partner] = percent(value.sum())   # no trade -> 0.0%
        top = in_year.sort_values("weight", ascending=False).head(1)
        row["largest partner"] = (top["partner"].iloc[0] if len(top)
                                  else "n/a")
        rows.append(row)
    return pd.DataFrame(rows)


def remittance_share_table(remit_w, macro):
    """Model share of remittances from Russia, and remittances % of GDP."""
    tjk = remit_w[remit_w["reporter"] == "TJK"]
    remit_gdp = macro[(macro["country"] == "TJK")
                      & (macro["variable"] == "remittances_gdp")]
    rows = []
    for year in SHARE_YEARS:
        russia = tjk[(tjk["year"] == year) & (tjk["partner"] == "RUS")]
        kazakhstan = tjk[(tjk["year"] == year) & (tjk["partner"] == "KAZ")]
        gdp_share = remit_gdp.loc[remit_gdp["year"] == year, "value"]
        rows.append({
            "year": year,
            "from Russia (model)": percent(russia["weight"].sum()
                                           if len(russia) else None),
            "from Kazakhstan (model)": percent(
                kazakhstan["weight"].sum() if len(kazakhstan) else None),
            "remittances, % of GDP": (round(gdp_share.iloc[0], 1)
                                      if len(gdp_share) else "n/a"),
        })
    return pd.DataFrame(rows)


def debt_lines(macro):
    """Share of public external debt owed to China in the latest year."""
    tjk = macro[macro["country"] == "TJK"]
    total = tjk[tjk["variable"] == "ppg_external_debt_usd"].set_index(
        "year")["value"]
    china = tjk[tjk["variable"] == "debt_to_china_usd"].set_index(
        "year")["value"]
    russia = tjk[tjk["variable"] == "debt_to_russia_usd"].set_index(
        "year")["value"]
    share = (china / total).dropna()
    lines = []
    if len(share) > 0:
        year = share.index.max()
        lines.append("- Owed to China in " + str(year) + ": "
                     + percent(share.loc[year])
                     + " of public external debt (US$ "
                     + str(round(china.loc[year] / 1e6)) + " million).")
    positive = russia[russia > 0]
    if len(positive) > 0:
        lines.append("- Last year with debt owed to Russia above zero: "
                     + str(positive.index.max()) + ".")
    return lines


def download_dates():
    """First and last download time from the download log."""
    path = RAW_DIR / "download_log.csv"
    if not path.exists():
        return "unknown (no download log)", "unknown"
    log = pd.read_csv(path)
    log = log[log["status"].astype(str) == "200"]
    if len(log) == 0:
        return "unknown (no successful downloads logged)", "unknown"
    return log["downloaded_at_utc"].min(), log["downloaded_at_utc"].max()


def main():
    trade_w = read_table("trade_weights")
    remit_w = read_table("remittance_weights")
    macro = read_table("macro")
    regressions = pd.read_csv(TABLE_DIR / "table03_regressions.csv")
    stationarity = pd.read_csv(TABLE_DIR / "table02_stationarity.csv")
    joint = pd.read_csv(TABLE_DIR / "table08_joint_tests.csv")
    correlations = pd.read_csv(TABLE_DIR
                               / "table09_regressor_correlations.csv")
    accuracy = pd.read_csv(TABLE_DIR / "table06_forecast_accuracy.csv")
    scenarios = pd.read_csv(TABLE_DIR / "table07_baseline_scenarios.csv")
    first_download, last_download = download_dates()

    lines = ["# Results summary (generated by src/07_results_summary.py)",
             "",
             "Created: " + datetime.datetime.now().strftime("%Y-%m-%d %H:%M"),
             "Data: " + WEO_VINTAGE_LABEL + "; downloads between "
             + str(first_download) + " and " + str(last_download) + " UTC.",
             "All results are associations in small annual samples, not "
             "causal effects. " + str(LAST_ACTUAL_YEAR)
             + " values are IMF estimates.",
             "",
             "## 1. Trade exposure: partner shares in Tajik goods trade",
             dataframe_to_markdown(trade_share_table(trade_w)),
             "## 2. Remittances (sources are model estimates)",
             dataframe_to_markdown(remittance_share_table(remit_w, macro)),
             "## 3. Public external debt by creditor"]
    lines += debt_lines(macro)
    lines += ["",
              "## 4. Stationarity tests (Tajik sample)",
              dataframe_to_markdown(stationarity.round(3)),
              "## 5. Regressions (Newey-West SE, 1 lag)",
              dataframe_to_markdown(regressions[[
                  "specification", "term", "coefficient", "std_error",
                  "p_value", "n", "years", "r_squared"]].round(3)),
              "Joint Wald tests (all partner coefficients = 0):",
              dataframe_to_markdown(joint.round(3)),
              "Correlations between regressors (Tajik sample):",
              dataframe_to_markdown(correlations),
              "## 6. Forecast accuracy (common sample of target years)",
              dataframe_to_markdown(accuracy.round(2)),
              "## 7. Outlook 2026-2030: partner model, scenarios and IMF",
              dataframe_to_markdown(scenarios[[
                  "scenario", "year", "forecast", "effect_vs_baseline",
                  "effect_se", "imf_forecast"]].round(2)),
              "See data/processed/data_quality_log.md for data checks."]

    SUMMARY_FILE.parent.mkdir(parents=True, exist_ok=True)
    with open(SUMMARY_FILE, "w", encoding="utf-8") as file:
        file.write("\n".join(lines) + "\n")
    print("Saved:", SUMMARY_FILE)


if __name__ == "__main__":
    main()
